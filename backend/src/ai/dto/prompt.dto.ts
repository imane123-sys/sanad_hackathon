import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsNotEmpty, IsOptional, IsString, IsNumber, Min, Max } from 'class-validator';

export class GeneratePromptDto {
  @ApiProperty({
    description: 'The user prompt or query to be processed by the LLM',
    example: 'أحتاج إلى مساعدة واستشارة قانونية عاجلة',
  })
  @IsString()
  @IsNotEmpty()
  prompt: string;

  @ApiPropertyOptional({
    description: 'Optional system instruction to guide the LLM behavior',
    example: 'You are SANAD assistant, providing supportive and safe guidance.',
  })
  @IsString()
  @IsOptional()
  systemInstruction?: string;

  @ApiPropertyOptional({
    description: 'Temperature for creativity/determinism (0.0 to 1.0)',
    default: 0.7,
    minimum: 0,
    maximum: 1,
  })
  @IsNumber()
  @IsOptional()
  @Min(0)
  @Max(1)
  temperature?: number;

  @ApiPropertyOptional({
    description: 'Optional user ID if authenticated',
    example: 'user-uuid-1234',
  })
  @IsString()
  @IsOptional()
  userId?: string;
}

export class GeneratePromptResponseDto {
  @ApiProperty({ description: 'The text response generated by the LLM' })
  text: string;

  @ApiProperty({ description: 'AI provider used', example: 'gemini' })
  provider: string;

  @ApiProperty({ description: 'Model name', example: 'gemini-1.5-pro' })
  model: string;

  @ApiPropertyOptional({ description: 'Total tokens used in request & response' })
  tokensUsed?: number;

  @ApiPropertyOptional({ description: 'Database interaction record ID if logged' })
  interactionId?: string;
}
